from fontTools.ttLib import TTFont
from .utils import rm_extension

import textwrap

class ASS:
    mono_font = "pipeline/fonts/RobotoMono-Medium.ttf"
    inter_font = "pipeline/fonts/Inter-Medium.otf"
    
    def __init__(self, video_data, config):
        self.video_data = video_data
        self.config = config
        

        
    def write_script(self):
        font_name = self.get_font_name()
        
        # Create a separate function or method that takes up the data and convert into usable form for bold, italic, alignment and etc.
        header = f"""[Script Info]
        ; Script Generated by Karasub
        ScriptType: v4.00+
        PlayResX: {self.video_data["resX"]}
        PlayResY: {self.video_data["resY"]}
        
        [V4+ Styles]
        Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
        Style: CustomKaraoke,{font_name},{self.config["font_size"]},{self.config["highlighted_word_color"]},{self.config["other_word_color"]},{self.config["outline_color"]},{self.config["shadow_color"]},{self.config["bold"]},{self.config["italic"]},0,0,100,100,0,0,1,{self.config["outline_enabled"]},{self.config["shadow_enabled"]},{self.config["alignment"]},7,7,33,1
        """
        
        body = textwrap.dedent(f"""\
        {header}
        [Events]
        Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
        """)
        
        for line in self.video_data["transcript"]:
            start_time = self.sec_to_hms(line["start"])
            end_time = self.sec_to_hms(line["end"])
            
            dialogue = f"Dialogue: 0,{start_time},{end_time},CustomKaraoke,,0,0,0,,"
            
            for word in line["words"]:
                ceptisec = (word["end"] - word["start"]) * 100
                # Rounding to closest integer.
                # ceptisec is 1/100 of a sec and \k values are only for the duration of "highlight".
                # Therefore, even if the value of ceptisec exceeds the duration of sentence by +1 value. It will not cause any issue.
                ceptisec = round(ceptisec)
                new_word = word["word"]
                
                if self.config["textcase"] == "uppercase":
                    new_word = new_word.upper()
                elif self.config["textcase"] == "lowercase":
                    new_word = new_word.lower()
                    
                dialogue += f"{{\k{ceptisec}}}{new_word["word"]} "
            
            dialogue = dialogue.strip() + "\n"
            body += dialogue
            
        return self.script_to_ass(body)
            
    def script_to_ass(self, body):
        path = "pipeline/temp/" + self.video_data["vid_path"].stem + ".ass"
        
        with open(path, "w") as file:
            file.write(body)
            
        return path
        
    def sec_to_hms(self, total_sec):
        mins, secs = divmod(total_sec, 60)
        hours, mins = divmod(mins, 60)
        
        hours = int(hours)
        mins = int(mins)

        return f"{hours:02d}:{mins:02d}:{secs:.2f}"        

    def get_font_name(self):
        selected_font = self.config["font_family"]
        font_path = ""
        
        if selected_font == "Inter":
            font_path = ASS.inter_font
        elif selected_font == "Roboto Mono":
            font_path = ASS.mono_font
        elif self.video_data["font_file"] != None:
            font_path = self.video_data["font_file"]
            
        font = TTFont(font_path)
        name_table = font["name"]
        
        for record in name_table.names:
            if record.nameID == 4:
                return record.toUnicode()
            
        return "Unknown"